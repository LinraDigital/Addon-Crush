local LOCALE_VERS_TABLE = {
    enUS = "en", enGB = "en", deDE = "de", esES = "es", esMX = "es",
    itIT = "it", ptBR = "pt", ptPT = "pt",
}

local langue = LOCALE_VERS_TABLE[GetLocale()]
local principale = langue and T[langue]
local secours = (langue and langue ~= "en") and T.en or nil

-- En français (ou langue inconnue sans table) : la clé est le texte
ns.L = setmetatable({}, {
    __index = function(t, cle)
        local v = (principale and principale[cle]) or (secours and secours[cle]) or cle
        rawset(t, cle, v)
        return v
    end,
})

-- Langue non prise en charge (ruRU, koKR…) : l'anglais par défaut
if not langue and GetLocale() ~= "frFR" then
    principale = T.en
end
